"""对象索引与位定义，依据随附手册 §5.1、§5.4、§5.7.3、§7.3 和 motor.eds。"""

from enum import IntEnum


class Object(IntEnum):
    """使用的对象字典索引；除身份对象外，子索引均为 0。"""

    IDENTITY = 0x1018
    CONTROLWORD = 0x6040
    STATUSWORD = 0x6041
    HALT_OPTION = 0x605D
    MODE = 0x6060
    MODE_DISPLAY = 0x6061
    # 实际位置的默认语义索引；Kinco可通过actual_position_index选手册6063，RS06用6064。
    ACTUAL_POSITION = 0x6064
    ACTUAL_VELOCITY = 0x606C
    TARGET_POSITION = 0x607A
    PROFILE_VELOCITY = 0x6081
    PROFILE_ACCELERATION = 0x6083
    PROFILE_DECELERATION = 0x6084


PP_MODE = 1
CW_SHUTDOWN = 0x0006
CW_SWITCH_ON = 0x0007
CW_ENABLE = 0x000F
CW_NEW_SETPOINT = 1 << 4
CW_CHANGE_IMMEDIATELY = 1 << 5
CW_RELATIVE = 1 << 6
CW_HALT = 1 << 8
SW_FAULT = 1 << 3
SW_TARGET_REACHED = 1 << 10
SW_LIMIT_ACTIVE = 1 << 11
SW_SETPOINT_ACK = 1 << 12
SW_FOLLOWING_ERROR = 1 << 13
# 只比较 DS402 状态相关位，忽略电压、远程控制和厂家扩展位。
STATE_MASK = 0x006F
STATE_READY = 0x0021
STATE_SWITCHED_ON = 0x0023
STATE_ENABLED = 0x0027
INT32_MIN = -(1 << 31)
INT32_MAX = (1 << 31) - 1
UINT32_MAX = (1 << 32) - 1
